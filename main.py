import math


def circle_area(r):
    """
    Вычисляет площадь круга по заданному радиусу.

    Формула: S = π * r²

    Параметры:
        r (float): радиус круга.

    Возвращаемое значение:
        float: площадь круга.

    Пример вызова:
        >>> circle_area(3)
        28.274333882308138
    """
    return math.pi * r * r


def circle_perimeter(r):
    """
    Вычисляет длину окружности (периметр круга) по заданному радиусу.

    Формула: P = 2 * π * r

    Параметры:
        r (float): радиус круга.

    Возвращаемое значение:
        float: длина окружности.

    Пример вызова:
        >>> circle_perimeter(3)
        18.84955592153876
    """
    return 2 * math.pi * r


def square_area(a):
    """
    Вычисляет площадь квадрата по длине его стороны.

    Формула: S = a²

    Параметры:
        a (float): длина стороны квадрата.

    Возвращаемое значение:
        float: площадь квадрата.

    Пример вызова:
        >>> square_area(4)
        16
    """
    return a * a


def square_perimeter(a):
    """
    Вычисляет периметр квадрата по длине его стороны.

    Формула: P = 4 * a

    Параметры:
        a (float): длина стороны квадрата.

    Возвращаемое значение:
        float: периметр квадрата.

    Пример вызова:
        >>> square_perimeter(4)
        16
    """
    return 4 * a


def rectangle_area(a, b):
    """
    Вычисляет площадь прямоугольника по длинам двух его сторон.

    Формула: S = a * b

    Параметры:
        a (float): длина первой стороны прямоугольника.
        b (float): длина второй стороны прямоугольника.

    Возвращаемое значение:
        float: площадь прямоугольника.

    Пример вызова:
        >>> rectangle_area(5, 3)
        15
    """
    return a * b


def rectangle_perimeter(a, b):
    """
    Вычисляет периметр прямоугольника по длинам двух его сторон.

    Формула: P = 2 * (a + b)

    Параметры:
        a (float): длина первой стороны прямоугольника.
        b (float): длина второй стороны прямоугольника.

    Возвращаемое значение:
        float: периметр прямоугольника.

    Пример вызова:
        >>> rectangle_perimeter(5, 3)
        16
    """
    return 2 * (a + b)


def triangle_area(a, b, c):
    """
    Вычисляет площадь треугольника по трём сторонам (формула Герона).

    Формула: S = √(p * (p - a) * (p - b) * (p - c)),
    где p — полупериметр: p = (a + b + c) / 2.

    Параметры:
        a (float): длина первой стороны треугольника.
        b (float): длина второй стороны треугольника.
        c (float): длина третьей стороны треугольника.

    Возвращаемое значение:
        float: площадь треугольника.

    Пример вызова:
        >>> triangle_area(3, 4, 5)
        6.0
    """
    p = (a + b + c) / 2
    return math.sqrt(p * (p - a) * (p - b) * (p - c))


def triangle_perimeter(a, b, c):
    """
    Вычисляет периметр треугольника по трём его сторонам.

    Формула: P = a + b + c

    Параметры:
        a (float): длина первой стороны треугольника.
        b (float): длина второй стороны треугольника.
        c (float): длина третьей стороны треугольника.

    Возвращаемое значение:
        float: периметр треугольника.

    Пример вызова:
        >>> triangle_perimeter(3, 4, 5)
        12
    """
    return a + b + c